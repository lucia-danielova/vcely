-- Run in the Supabase SQL editor for project mwvtwfmerozjelyymmxg

create extension if not exists postgis;

create table if not exists public.vcelnice (
  id bigint generated by default as identity primary key,
  nazov text not null,
  pocet_rodin integer not null default 1,
  email text,
  cevz text,
  lat double precision not null,
  lng double precision not null,
  typ_stanovista text default 'permanent',
  znaska_tagy text,
  geom geography(point, 4326)
    generated always as (
      st_setsrid(st_makepoint(lng, lat), 4326)::geography
    ) stored,
  created_at timestamptz not null default now()
);

create index if not exists vcelnice_geom_gix on public.vcelnice using gist (geom);

create table if not exists public.evidencia_postrekov (
  id bigint generated by default as identity primary key,
  parcela text,
  plocha_ha numeric,
  pripravok text,
  vietor_ms numeric,
  teplota_c numeric,
  termin text,
  toxicita text,
  okno_postreku text,
  lat double precision,
  lng double precision,
  geom geography(point, 4326),
  created_at timestamptz not null default now()
);

create or replace function public.get_apiaries_in_buffer(
  spray_lat double precision,
  spray_lng double precision,
  radius_meters double precision default 3000
)
returns table (
  hive_id bigint,
  hive_name text,
  hive_count integer,
  hive_email text,
  hive_cevz text,
  lat double precision,
  lng double precision,
  distance_meters double precision
)
language sql
stable
as $$
  select
    v.id as hive_id,
    v.nazov as hive_name,
    v.pocet_rodin as hive_count,
    v.email as hive_email,
    v.cevz as hive_cevz,
    v.lat,
    v.lng,
    st_distance(
      v.geom,
      st_setsrid(st_makepoint(spray_lng, spray_lat), 4326)::geography
    ) as distance_meters
  from public.vcelnice v
  where v.geom is not null
    and st_dwithin(
      v.geom,
      st_setsrid(st_makepoint(spray_lng, spray_lat), 4326)::geography,
      radius_meters
    )
  order by distance_meters asc;
$$;

-- Demo RLS: public read/write for the anon key (tighten for production).
alter table public.vcelnice enable row level security;
alter table public.evidencia_postrekov enable row level security;

drop policy if exists "vcelnice_anon_all" on public.vcelnice;
create policy "vcelnice_anon_all" on public.vcelnice
  for all to anon, authenticated using (true) with check (true);

drop policy if exists "evidencia_anon_all" on public.evidencia_postrekov;
create policy "evidencia_anon_all" on public.evidencia_postrekov
  for all to anon, authenticated using (true) with check (true);

grant usage on schema public to anon, authenticated;
grant select, insert, update, delete on public.vcelnice to anon, authenticated;
grant select, insert, update, delete on public.evidencia_postrekov to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;
grant execute on function public.get_apiaries_in_buffer(double precision, double precision, double precision) to anon, authenticated;
