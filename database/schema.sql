-- ============================================================================
-- POSTGIS RPC FUNKCIA: KONTROLA 3 000 M OCHRANNÉHO PÁSMA VČIEL CEZ INDEX GIST
-- ============================================================================

CREATE OR REPLACE FUNCTION public.check_spray_collision_optimized(
    spray_lat DOUBLE PRECISION,
    spray_lng DOUBLE PRECISION,
    radius_meters DOUBLE PRECISION DEFAULT 3000
)
RETURNS TABLE (
    hive_id BIGINT,
    hive_name VARCHAR,
    hive_count INT,
    hive_email VARCHAR,
    hive_cevz VARCHAR,
    lat DOUBLE PRECISION,
    lng DOUBLE PRECISION,
    distance_meters DOUBLE PRECISION
) 
LANGUAGE plpgsql
SECURITY DEFINER
AS $$ DECLARE spray_point geography; BEGIN spray_point := ST_SetSRID(ST_MakePoint(spray_lng, spray_lat), 4326)::geography;      RETURN QUERY SELECT h.id AS hive_id, h.name AS hive_name, h.count AS hive_count, h.email AS hive_email, h.cevz AS hive_cevz, h.lat, h.lng, ST_Distance(h.geom, spray_point) AS distance_meters FROM public.hives h WHERE ST_DWithin(h.geom, spray_point, radius_meters) ORDER BY distance_meters ASC; END; $$;