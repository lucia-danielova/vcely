CREATE OR REPLACE FUNCTION public.check_spray_collision_optimized(
    spray_lat DOUBLE PRECISION,
    spray_lng DOUBLE PRECISION,
    radius_meters DOUBLE PRECISION DEFAULT 3000
)
RETURNS TABLE (
    hive_id BIGINT,
    hive_name VARCHAR,
    hive_count INTEGER,
    hive_email VARCHAR,
    hive_cevz VARCHAR,
    lat DOUBLE PRECISION,
    lng DOUBLE PRECISION,
    distance_meters DOUBLE PRECISION
)
LANGUAGE sql
STABLE
AS $$
    SELECT h.id, h.name, h.colony_count, h.contact_email, h.cevz,
           ST_Y(h.geom::geometry), ST_X(h.geom::geometry),
           ST_Distance(h.geom, ST_SetSRID(ST_MakePoint(spray_lng, spray_lat), 4326)::geography)
    FROM public.hives h
    WHERE ST_DWithin(h.geom, ST_SetSRID(ST_MakePoint(spray_lng, spray_lat), 4326)::geography, radius_meters)
    ORDER BY ST_Distance(h.geom, ST_SetSRID(ST_MakePoint(spray_lng, spray_lat), 4326)::geography);
$$;

-- BBOX dopyt podľa ZBGIS vzoru: vráti parcely pretínajúce zobrazený výrez mapy
-- ako GeoJSON FeatureCollection. Bezpečné voči SQL injekcii (len parametre),
-- bez citlivých údajov vlastníkov a s horným limitom počtu záznamov.
CREATE OR REPLACE FUNCTION public.map_parcels_geojson(
    p_min_lng DOUBLE PRECISION,
    p_min_lat DOUBLE PRECISION,
    p_max_lng DOUBLE PRECISION,
    p_max_lat DOUBLE PRECISION
) RETURNS json
LANGUAGE sql
STABLE
AS $$
    SELECT json_build_object(
        'type', 'FeatureCollection',
        'features', COALESCE(json_agg(ST_AsGeoJSON(t.*)::json), '[]'::json)
    )
    FROM (
        SELECT id, external_register_id, area_ha, crop, geom
        FROM public.user_parcels
        WHERE ST_Intersects(
            geom,
            ST_MakeEnvelope(p_min_lng, p_min_lat, p_max_lng, p_max_lat, 4326)
        )
        ORDER BY id
        LIMIT 2000
    ) AS t;
$$;

