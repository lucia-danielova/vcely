-- 1. Vymazanie predchádzajúcich tabuliek a testovacích dát (Čistý štart)
DROP FUNCTION IF EXISTS check_spray_collision_optimized(DOUBLE PRECISION, DOUBLE PRECISION, DOUBLE PRECISION) CASCADE;
DROP TABLE IF EXISTS spray_alerts CASCADE;
DROP TABLE IF EXISTS lpis_parcels CASCADE;
DROP TABLE IF EXISTS cadastre_parcels_cache CASCADE;
DROP TABLE IF EXISTS hives CASCADE;
DROP TABLE IF EXISTS registered_entities CASCADE;
