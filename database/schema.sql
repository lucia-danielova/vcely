CREATE OR REPLACE FUNCTION public.get_apiaries_in_buffer(
    lat DOUBLE PRECISION,
    lng DOUBLE PRECISION,
    radius_meters DOUBLE PRECISION DEFAULT 3000
)
RETURNS TABLE (
    hive_id BIGINT,
    hive_name VARCHAR,
    hive_count INTEGER,
    hive_email VARCHAR,
    hive_cevz VARCHAR,
    lat DOUBLE PRECISION,
    lng DOUBLE PRECISION,
    distance_meters DOUBLE PRECISION
)
LANGUAGE plpgsql
STABLE
AS $$
BEGIN
    RETURN QUERY
    SELECT *
    FROM (
        SELECT v.id, v.name::varchar, v.colony_count, v.email::varchar, v.cevz::varchar, v.lat, v.lng,
               ST_Distance(
                   ST_SetSRID(ST_MakePoint(v.lng, v.lat), 4326)::geography,
                   ST_SetSRID(ST_MakePoint(get_apiaries_in_buffer.lng, get_apiaries_in_buffer.lat), 4326)::geography
               ) AS distance_meters
        FROM public.vcelnice v
        WHERE ST_DWithin(
            ST_SetSRID(ST_MakePoint(v.lng, v.lat), 4326)::geography,
            ST_SetSRID(ST_MakePoint(get_apiaries_in_buffer.lng, get_apiaries_in_buffer.lat), 4326)::geography,
            get_apiaries_in_buffer.radius_meters
        )
        UNION ALL
        SELECT h.id, h.name::varchar, h.colony_count, h.contact_email::varchar, h.cevz::varchar,
               ST_Y(h.geom::geometry), ST_X(h.geom::geometry),
               ST_Distance(
                   h.geom,
                   ST_SetSRID(ST_MakePoint(get_apiaries_in_buffer.lng, get_apiaries_in_buffer.lat), 4326)::geography
               ) AS distance_meters
        FROM public.hives h
        WHERE ST_DWithin(
            h.geom,
            ST_SetSRID(ST_MakePoint(get_apiaries_in_buffer.lng, get_apiaries_in_buffer.lat), 4326)::geography,
            get_apiaries_in_buffer.radius_meters
        )
    ) AS apiaries
    ORDER BY apiaries.distance_meters;
END;
$$;
