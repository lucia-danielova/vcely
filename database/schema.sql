CREATE OR REPLACE FUNCTION public.get_apiaries_in_buffer(
    p_lat DOUBLE PRECISION,
    p_lng DOUBLE PRECISION,
    p_radius_m DOUBLE PRECISION DEFAULT 3000
)
RETURNS TABLE (
    hive_id BIGINT,
    hive_name VARCHAR,
    hive_count INTEGER,
    hive_email VARCHAR,
    hive_cevz VARCHAR,
    lat DOUBLE PRECISION,
    lng DOUBLE PRECISION,
    distance_meters DOUBLE PRECISION
)
LANGUAGE sql
STABLE
AS $$
    SELECT
        v.id,
        v.nazov,
        v.pocet_rodin,
        v.email,
        v.cevz,
        COALESCE(v.lat, ST_Y(v.geom::geometry)),
        COALESCE(v.lng, ST_X(v.geom::geometry)),
        ST_Distance(
            COALESCE(v.geom, ST_SetSRID(ST_MakePoint(v.lng, v.lat), 4326)::geography),
            ST_SetSRID(ST_MakePoint(p_lng, p_lat), 4326)::geography
        )
    FROM public.vcelnice v
    WHERE v.lat IS NOT NULL
      AND v.lng IS NOT NULL
      AND ST_DWithin(
            COALESCE(v.geom, ST_SetSRID(ST_MakePoint(v.lng, v.lat), 4326)::geography),
            ST_SetSRID(ST_MakePoint(p_lng, p_lat), 4326)::geography,
            p_radius_m
          )
    ORDER BY 8;
$$;

