-- 2. Aktivácia priestorového rozšírenia PostGIS
CREATE EXTENSION IF NOT EXISTS postgis;

-- 3. Tabuľka používateľských profilov (prepojená so Supabase Auth)
CREATE TABLE public.user_profiles (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    auth_user_id UUID UNIQUE,
    role VARCHAR(32) NOT NULL DEFAULT 'AGRO',
    persona VARCHAR(32) NOT NULL DEFAULT 'AGRO_PRO',
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) UNIQUE NOT NULL,
    ico VARCHAR(32),
    cevz VARCHAR(64),
    phone VARCHAR(64),
    address TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Tabuľka subjektov načítaných naživo zo štátneho API RegisterUZ.sk (MF SR)
CREATE TABLE public.registered_entities (
    ico VARCHAR(32) PRIMARY KEY,
    dic VARCHAR(32),
    name VARCHAR(255) NOT NULL,
    type VARCHAR(255),
    address TEXT,
    city VARCHAR(120),
    street VARCHAR(120),
    lat DOUBLE PRECISION,
    lng DOUBLE PRECISION,
    source VARCHAR(120) DEFAULT 'API RegisterUZ.sk',
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. Tabuľka parciel načítaných naživo z ArcGIS REST API Katastra ÚGKK SR (C-KN / E-KN)
CREATE TABLE public.cadastre_parcels_cache (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    register VARCHAR(4) NOT NULL DEFAULT 'C',
    parcel_number VARCHAR(64) NOT NULL,
    ku_name VARCHAR(120) NOT NULL,
    ku_code VARCHAR(16),
    obec VARCHAR(150),
    okres VARCHAR(100),
    lv_number VARCHAR(32),
    druh_pozemku VARCHAR(150),
    area_sqm NUMERIC(12, 2),
    area_ha NUMERIC(10, 2),
    center_lat DOUBLE PRECISION NOT NULL,
    center_lng DOUBLE PRECISION NOT NULL,
    coords_json JSONB NOT NULL,
    source VARCHAR(120) DEFAULT 'API ÚGKK SR ZBGIS',
    created_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(register, ku_name, parcel_number)
);

-- 6. Tabuľka pôdnych blokov LPIS (PPA / vlastné zamerané parcely poľnohospodárov)
CREATE TABLE public.lpis_parcels (
    id VARCHAR(64) PRIMARY KEY,
    owner_ico VARCHAR(32),
    owner_name VARCHAR(255) NOT NULL,
    owner_email VARCHAR(255),
    ku_name VARCHAR(120),
    crop VARCHAR(255) NOT NULL,
    kultura VARCHAR(120) DEFAULT 'Orná pôda (OP)',
    area_ha NUMERIC(10, 2) NOT NULL,
    center_lat DOUBLE PRECISION NOT NULL,
    center_lng DOUBLE PRECISION NOT NULL,
    coords_json JSONB NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 7. Tabuľka stanovíšť včelstiev (CEVZ a registrovaní včelári v teréne)
CREATE TABLE public.hives (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_email VARCHAR(255),
    name VARCHAR(255) NOT NULL,
    count INT NOT NULL DEFAULT 10,
    cevz VARCHAR(100) DEFAULT 'CEVZ-SR',
    email VARCHAR(255) NOT NULL,
    lat DOUBLE PRECISION NOT NULL,
    lng DOUBLE PRECISION NOT NULL,
    geom GEOGRAPHY(Point, 4326) GENERATED ALWAYS AS (ST_SetSRID(ST_MakePoint(lng, lat), 4326)::geography) STORED,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX idx_hives_geom ON public.hives USING GIST (geom);

-- 8. Tabuľka zákonných hlásení o postrekoch (48h legislatívna notifikácia)
CREATE TABLE public.spray_alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_name VARCHAR(255) NOT NULL,
    sender_email VARCHAR(255),
    location_label VARCHAR(255) NOT NULL,
    lat DOUBLE PRECISION NOT NULL,
    lng DOUBLE PRECISION NOT NULL,
    affected_hives_count INT DEFAULT 0,
    affected_colonies INT DEFAULT 0,
    recipients JSONB DEFAULT '[]'::jsonb,
    note TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

