    lng DOUBLE PRECISION,
    geom geography(Point, 4326),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS vcelnice_geom_idx ON public.vcelnice USING GIST (geom);

CREATE OR REPLACE FUNCTION public.vcelnice_sync_geom()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.lat IS NOT NULL AND NEW.lng IS NOT NULL THEN
        NEW.geom := ST_SetSRID(ST_MakePoint(NEW.lng, NEW.lat), 4326)::geography;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_vcelnice_geom ON public.vcelnice;
CREATE TRIGGER trg_vcelnice_geom
BEFORE INSERT OR UPDATE ON public.vcelnice
FOR EACH ROW EXECUTE PROCEDURE public.vcelnice_sync_geom();

