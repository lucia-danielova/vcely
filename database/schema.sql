CREATE UNIQUE INDEX IF NOT EXISTS app_users_cevz_unique ON public.app_users (cevz) WHERE cevz IS NOT NULL;

-- Automatická údržba updated_at (podľa plánu z dokumentu: univerzálny trigger
-- namiesto ručného nastavovania v každom UPDATE).
CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_app_users_updated_at ON public.app_users;
CREATE TRIGGER trg_app_users_updated_at
BEFORE UPDATE ON public.app_users
FOR EACH ROW EXECUTE PROCEDURE public.set_updated_at();

