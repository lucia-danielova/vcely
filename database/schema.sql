-- AGROGIS initial schema. Safe to run repeatedly; does not drop existing tables or data.
CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE IF NOT EXISTS public.app_users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    email VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(32) NOT NULL CHECK (role IN ('AGRO', 'AGRO_PRO', 'BEEKEEPER', 'BEE_HOBBY', 'BEE_BEGINNER', 'GARDENER', 'GARDEN_NEW')),
    name VARCHAR(255) NOT NULL,
    ico VARCHAR(10),
    cevz VARCHAR(64),
    phone VARCHAR(64),
    address TEXT,
    lpis_id VARCHAR(64),
    profile_location_lat DOUBLE PRECISION,
    profile_location_lng DOUBLE PRECISION,
    company_name VARCHAR(255),
    is_verified BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Idempotent upgrades for databases created before the profile metadata and role extensions.
ALTER TABLE public.app_users ADD COLUMN IF NOT EXISTS lpis_id VARCHAR(64);
ALTER TABLE public.app_users ADD COLUMN IF NOT EXISTS profile_location_lat DOUBLE PRECISION;
ALTER TABLE public.app_users ADD COLUMN IF NOT EXISTS profile_location_lng DOUBLE PRECISION;
ALTER TABLE public.app_users ADD COLUMN IF NOT EXISTS company_name VARCHAR(255);
ALTER TABLE public.app_users DROP CONSTRAINT IF EXISTS app_users_role_check;
ALTER TABLE public.app_users ADD CONSTRAINT app_users_role_check
    CHECK (role IN ('AGRO', 'AGRO_PRO', 'BEEKEEPER', 'BEE_HOBBY', 'BEE_BEGINNER', 'GARDENER', 'GARDEN_NEW'));

CREATE UNIQUE INDEX IF NOT EXISTS app_users_email_lower_unique ON public.app_users (LOWER(email));
CREATE INDEX IF NOT EXISTS app_users_ico_idx ON public.app_users (ico) WHERE ico IS NOT NULL;
CREATE INDEX IF NOT EXISTS app_users_lpis_idx ON public.app_users (lpis_id) WHERE lpis_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS app_users_cevz_unique ON public.app_users (cevz) WHERE cevz IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.registered_entities (
    ico VARCHAR(10) PRIMARY KEY,
    dic VARCHAR(32),
    name VARCHAR(255) NOT NULL,
    type VARCHAR(255),
    address TEXT,
    city VARCHAR(120),
    lat DOUBLE PRECISION,
    lng DOUBLE PRECISION,
    source VARCHAR(120) NOT NULL DEFAULT 'RegisterUZ.sk',
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS registered_entities_name_idx ON public.registered_entities USING GIN (to_tsvector('simple', name));
CREATE INDEX IF NOT EXISTS registered_entities_city_idx ON public.registered_entities (city);

CREATE TABLE IF NOT EXISTS public.user_parcels (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES public.app_users(id) ON DELETE CASCADE,
    external_register_id VARCHAR(100) NOT NULL,
    geom geometry(Polygon, 4326) NOT NULL,
    area_ha NUMERIC(10, 2) NOT NULL DEFAULT 0,
    crop VARCHAR(255) NOT NULL DEFAULT 'Neurčená plodina',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS user_parcels_user_id_idx ON public.user_parcels (user_id);
CREATE INDEX IF NOT EXISTS user_parcels_geom_idx ON public.user_parcels USING GIST (geom);

CREATE TABLE IF NOT EXISTS public.hives (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id UUID REFERENCES public.app_users(id) ON DELETE SET NULL,
    name VARCHAR(255) NOT NULL,
    colony_count INTEGER NOT NULL DEFAULT 1 CHECK (colony_count > 0),
    cevz VARCHAR(100),
    contact_email VARCHAR(255),
    geom geography(Point, 4326) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS hives_geom_idx ON public.hives USING GIST (geom);

CREATE TABLE IF NOT EXISTS public.spray_alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id UUID REFERENCES public.app_users(id) ON DELETE SET NULL,
    location_label VARCHAR(255) NOT NULL,
    geom geography(Point, 4326) NOT NULL,
    note TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS spray_alerts_geom_idx ON public.spray_alerts USING GIST (geom);

CREATE OR REPLACE FUNCTION public.check_spray_collision_optimized(
    spray_lat DOUBLE PRECISION,
    spray_lng DOUBLE PRECISION,
    radius_meters DOUBLE PRECISION DEFAULT 3000
)
RETURNS TABLE (
    hive_id BIGINT,
    hive_name VARCHAR,
    hive_count INTEGER,
    hive_email VARCHAR,
    hive_cevz VARCHAR,
    lat DOUBLE PRECISION,
    lng DOUBLE PRECISION,
    distance_meters DOUBLE PRECISION
)
LANGUAGE sql
STABLE
AS $$
    SELECT h.id, h.name, h.colony_count, h.contact_email, h.cevz,
           ST_Y(h.geom::geometry), ST_X(h.geom::geometry),
           ST_Distance(h.geom, ST_SetSRID(ST_MakePoint(spray_lng, spray_lat), 4326)::geography)
    FROM public.hives h
    WHERE ST_DWithin(h.geom, ST_SetSRID(ST_MakePoint(spray_lng, spray_lat), 4326)::geography, radius_meters)
    ORDER BY ST_Distance(h.geom, ST_SetSRID(ST_MakePoint(spray_lng, spray_lat), 4326)::geography);
$$;
